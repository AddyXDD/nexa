/**
 * SEO head management for a client-rendered SPA.
 *
 * Vite emits a single `index.html` for every route, so the static tags in
 * that file describe the homepage and nothing else. Without correction, every
 * other route inherits the homepage's title, description *and canonical* —
 * which is what made `/terms` and `/privacy` declare themselves duplicates of
 * `/`. Route components call `useSeo` after mount to fix that: title,
 * description, canonical, Open Graph, Twitter card, robots directive, and the
 * route's own JSON-LD. Google evaluates the rendered DOM, so these are the
 * tags that count.
 *
 * Site-wide entities (Organization, WebSite) stay static in `index.html`;
 * only route-specific schema is injected here, so nothing is duplicated.
 */

/**
 * The origin the deployment actually serves from. The apex domain
 * (`nexameet.in`) 308-redirects to `www.nexameet.in`, so www is the canonical
 * host — every canonical URL, sitemap entry and structured-data `@id` must
 * agree with it or the signals point at a redirect.
 */
export const SITE_URL = "https://www.nexameet.in";

export const SITE_NAME = "Nexa Meet";

/** 1200×630 social card, generated by `scripts/generate-og-image.mjs`. */
export const OG_IMAGE_URL = `${SITE_URL}/og.png`;

/** Public pages: indexable, full snippets, large image previews. */
export const INDEX_ROBOTS =
  "index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1";

/**
 * Account, admin, room, callback and error surfaces: never indexed. Set as a
 * meta tag here and as an `X-Robots-Tag` header in `vercel.json`.
 */
export const NOINDEX_ROBOTS = "noindex, nofollow";

export type JsonLdNode = Record<string, unknown>;

export type SeoConfig = {
  title: string;
  description: string;
  /**
   * Route path, always starting with "/" ("/" is the homepage). Omit on
   * surfaces that must not claim a canonical URL at all (404s), which drops
   * the canonical and `og:url` tags instead of pointing them somewhere wrong.
   */
  path?: string;
  /** Defaults to {@link INDEX_ROBOTS}. */
  robots?: string;
  /** Absolute URL; defaults to the site-wide social card. */
  image?: string;
  /** Route-specific JSON-LD graphs. */
  jsonLd?: readonly JsonLdNode[];
};

/** Marks head elements this module owns, so they can be found and removed. */
const MANAGED = "data-nexa-seo";

function upsertMeta(property: string, content: string): void {
  let node = document.head.querySelector(`meta[property="${property}"]`);
  if (!node) {
    node = document.createElement("meta");
    node.setAttribute(MANAGED, "");
    document.head.appendChild(node);
  }
  node.setAttribute("property", property);
  node.setAttribute("content", content);
}

function upsertName(name: string, content: string): void {
  let node = document.head.querySelector(`meta[name="${name}"]`);
  if (!node) {
    node = document.createElement("meta");
    node.setAttribute(MANAGED, "");
    document.head.appendChild(node);
  }
  node.setAttribute("name", name);
  node.setAttribute("content", content);
}

function removeMeta(selector: string): void {
  document.head.querySelector(selector)?.remove();
}

/**
 * Apply a page's tags. Returns a cleanup that removes the JSON-LD scripts it
 * injected — the title, description and canonical stay in place until the
 * next route overwrites them, so a transition never flashes an empty head.
 */
export function applySeo({
  title,
  description,
  path,
  robots = INDEX_ROBOTS,
  image = OG_IMAGE_URL,
  jsonLd,
}: SeoConfig): () => void {
  if (typeof document === "undefined") return () => {};

  document.title = title;
  upsertName("description", description);
  upsertName("robots", robots);
  upsertMeta("og:title", title);
  upsertMeta("og:description", description);
  upsertMeta("og:type", "website");
  upsertMeta("og:site_name", SITE_NAME);
  upsertMeta("og:locale", "en_US");
  upsertMeta("og:image", image);
  upsertMeta("og:image:type", "image/png");
  upsertMeta("og:image:width", "1200");
  upsertMeta("og:image:height", "630");
  upsertMeta("og:image:alt", `${SITE_NAME} — private video meetings`);
  upsertName("twitter:card", "summary_large_image");
  upsertName("twitter:title", title);
  upsertName("twitter:description", description);
  upsertName("twitter:image", image);

  const canonical = document.head.querySelector('link[rel="canonical"]');
  if (path === undefined) {
    canonical?.remove();
    removeMeta('meta[property="og:url"]');
  } else {
    const href = `${SITE_URL}${path}`;
    let link = canonical;
    if (!link) {
      link = document.createElement("link");
      link.setAttribute(MANAGED, "");
      document.head.appendChild(link);
    }
    link.setAttribute("rel", "canonical");
    link.setAttribute("href", href);
    upsertMeta("og:url", href);
  }

  const injected: HTMLScriptElement[] = [];
  for (const node of jsonLd ?? []) {
    const script = document.createElement("script");
    script.type = "application/ld+json";
    script.setAttribute(MANAGED, "");
    script.textContent = JSON.stringify(node);
    document.head.appendChild(script);
    injected.push(script);
  }

  return () => {
    for (const script of injected) script.remove();
  };
}

/** BreadcrumbList for a single top-level page beneath the homepage. */
export function breadcrumbList(name: string, path: string): JsonLdNode {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: [
      {
        "@type": "ListItem",
        position: 1,
        name: SITE_NAME,
        item: `${SITE_URL}/`,
      },
      {
        "@type": "ListItem",
        position: 2,
        name,
        item: `${SITE_URL}${path}`,
      },
    ],
  };
}
